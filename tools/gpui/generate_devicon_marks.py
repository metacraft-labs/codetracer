#!/usr/bin/env python3
"""Generate src/frontend/gpui/devicon_marks.nim: the desktop's file-type marks.

The Electron front-end draws a file's type mark in its tree with the
`devicon` icon font (`src/public/resources/fonts/devicon.ttf`), choosing the
glyph from the file's extension (`src/frontend/ui/filesystem.nim`'s
ICON_MAP, resolved to code points through
`src/public/third_party/devicon.min.css`). The GPUI front-end draws the same
outlines as SVG documents, so no icon font has to be found at run time.

Run from the repository root with fontTools available:
    nix shell --impure --expr 'with import <nixpkgs> {}; \
      python3.withPackages (p: [p.fonttools])' \
      --command python3 tools/gpui/generate_devicon_marks.py
"""
import re
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
CSS = ROOT / "src/public/third_party/devicon.min.css"
MAP = ROOT / "src/frontend/ui/filesystem.nim"
FONT = ROOT / "src/public/resources/fonts/devicon.ttf"
OUT = ROOT / "src/frontend/gpui/devicon_marks.nim"

css = CSS.read_text(encoding="utf-8")
classes = dict(re.findall(r'\.(devicon-[a-z0-9-]+):before\{content:"(.)"\}', css))
pairs = re.findall(r'"([a-z0-9]+)"(?:\.cstring)?:\s*"(devicon-[a-z0-9-]+)"',
                   MAP.read_text(encoding="utf-8"))
font = TTFont(str(FONT))
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm
ascent = font["hhea"].ascent

marks = {}
rows = []
for ext, cls in pairs:
    if cls not in classes:
        continue
    cp = ord(classes[cls])
    name = cmap.get(cp)
    if name is None:
        continue
    if cp not in marks:
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(pen)
        marks[cp] = pen.getCommands()
    rows.append((ext, cp))

lines = [
    "## devicon_marks.nim — GENERATED by tools/gpui/generate_devicon_marks.py;",
    "## do not edit. The desktop's file-type marks (the `devicon` font's",
    "## outlines, by extension), as SVG documents whose fill is `currentColor`.",
    "",
    "const",
    "  DeviconByExtension* = [",
]
for ext, cp in rows:
    lines.append(f'    ("{ext}", 0x{cp:X}),')
lines.append("  ]")
lines.append("  DeviconSvgs* = [")
for cp, d in sorted(marks.items()):
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" '
           f'viewBox="0 {-ascent} {upm} {upm}"><path fill="currentColor" '
           f'transform="scale(1,-1)" d="{d}"/></svg>')
    lines.append(f'    (0x{cp:X}, """{svg}"""),')
lines.append("  ]")
lines.append("")
lines.append("func deviconSvgFor*(name: string): string =")
lines.append("  ## The mark for a file `name` by its extension, or \"\" for none.")
lines.append("  var ext = name")
lines.append("  let dot = name.rfind('.')")
lines.append("  if dot >= 0: ext = name[dot + 1 .. ^1]")
lines.append("  ext = ext.toLowerAscii")
lines.append("  for (e, cp) in DeviconByExtension:")
lines.append("    if e == ext:")
lines.append("      for (c, svg) in DeviconSvgs:")
lines.append("        if c == cp: return svg")
lines.append('  ""')
OUT.write_text("import std/strutils\n\n" + "\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT} ({len(rows)} extensions, {len(marks)} marks)")
