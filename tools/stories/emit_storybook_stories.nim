## Writes CodeTracer's StoryBook stories from their one declaration.
##
## Every story is declared in `src/frontend/stories/codetracer_stories.nim`,
## which the IsoNim Editor instance reads too. This tool turns each section
## into a CSF file, `storybook/stories/generated/<module>.stories.js`, whose
## stories call `story()` from `storybook/stories/lib/csf.js`, and writes
## `storybook/stories/generated/stories.json`: the StoryBook id, title and
## export of every story, which the editor smoke check and reviewers compare
## against what StoryBook indexed.
##
## The generated directory is git-ignored and rewritten whole: a story removed
## from the declaration disappears from StoryBook on the next run, and a file
## of a section that no longer exists is deleted.
##
##   nim r tools/stories/emit_storybook_stories.nim [--out:<dir>] [--check]
##
## `--check` writes nothing and exits 1 when the generated directory differs
## from what the declaration produces (used to tell whether a StoryBook build
## is stale). The declaration is validated first; an invalid one exits 2.

import std/[json, os, parseopt, sets, strutils, tables]
import ../../src/frontend/stories/codetracer_stories

const
  generatedHeader = "// GENERATED by tools/stories/emit_storybook_stories.nim from\n" &
    "// src/frontend/stories/codetracer_stories.nim. Do not edit: change the\n" &
    "// declaration and run `just storybook-stories`.\n"

proc jsString(s: string): string =
  ## A JavaScript string literal for `s` (JSON string syntax is valid JS).
  escapeJson(s)

proc startCase(exportName: string): string =
  ## StoryBook's `storyNameFromExport` (lodash `startCase`): split a
  ## PascalCase export into words. `LiveMcrDebugControls` -> "Live Mcr Debug
  ## Controls". https://storybook.js.org/docs/api/csf#named-story-exports
  for i, c in exportName:
    if i > 0 and c in {'A'..'Z'}:
      let prev = exportName[i - 1]
      let nextLower = i + 1 < exportName.len and exportName[i + 1] in {'a'..'z'}
      if prev in {'a'..'z', '0'..'9'} or (prev in {'A'..'Z'} and nextLower):
        result.add ' '
    elif i > 0 and c in {'0'..'9'} and exportName[i - 1] notin {'0'..'9'}:
      result.add ' '
    result.add c

proc sanitize(s: string): string =
  ## StoryBook's id sanitiser (`@storybook/csf` `sanitize`): lower case, every
  ## run of other characters one dash, no leading or trailing dash.
  var dash = false
  for c in s.toLowerAscii:
    if c in {'a'..'z', '0'..'9'}:
      if dash and result.len > 0: result.add '-'
      dash = false
      result.add c
    else:
      dash = true

proc storybookId*(section: CodeTracerStorySection; story: CodeTracerStory): string =
  sanitize(section.title) & "--" & sanitize(startCase(story.exportName))

proc csfModule(section: CodeTracerStorySection): string =
  result = generatedHeader & "\n"
  result.add "import { story } from \"../lib/csf.js\";\n\n"
  result.add "// " & section.description & ".\n"
  result.add "export default {\n"
  result.add "  title: " & jsString(section.title) & ",\n"
  result.add "  parameters: { layout: \"fullscreen\" },\n"
  result.add "};\n\n"
  for story in section.stories:
    result.add "export const " & story.exportName & " = story(" &
      jsString(story.kind) & ", " & jsString(story.surface) & ", " &
      jsString(story.fixture) & ", " & jsString(story.name) &
      (if story.check.len > 0 or story.frameTitle.len > 0: ", " & jsString(story.check) else: "") &
      (if story.frameTitle.len > 0: ", " & jsString(story.frameTitle) else: "") & ");\n"

proc storyIndex(sections: seq[CodeTracerStorySection]): string =
  var stories = newJArray()
  for section in sections:
    for story in section.stories:
      stories.add %*{
        "id": storybookId(section, story),
        "title": section.title,
        "exportName": story.exportName,
        "name": story.name,
        "editorGroup": section.group,
        "kind": story.kind,
        "surface": story.surface,
        "fixture": story.fixture,
      }
  pretty(%*{"generatedBy": "tools/stories/emit_storybook_stories.nim",
            "stories": stories}) & "\n"

proc expectedFiles(sections: seq[CodeTracerStorySection]): OrderedTable[string, string] =
  for section in sections:
    result[section.module & ".stories.js"] = csfModule(section)
  result["stories.json"] = storyIndex(sections)

proc main(): int =
  var outDir = currentSourcePath().parentDir.parentDir.parentDir /
    "storybook" / "stories" / "generated"
  var check = false
  for kind, key, val in getopt():
    case kind
    of cmdLongOption, cmdShortOption:
      case key
      of "out": outDir = absolutePath(val)
      of "check": check = true
      else:
        stderr.writeLine "emit_storybook_stories: unknown option --" & key
        return 2
    of cmdArgument:
      stderr.writeLine "emit_storybook_stories: unexpected argument " & key
      return 2
    of cmdEnd: discard

  let sections = codeTracerStorySections()
  let problems = validateStorySections(sections)
  if problems.len > 0:
    for problem in problems:
      stderr.writeLine "emit_storybook_stories: invalid declaration: " & problem
    return 2
  # Two sections must not produce the same StoryBook id either.
  var ids: HashSet[string]
  for section in sections:
    for story in section.stories:
      let id = storybookId(section, story)
      if id in ids:
        stderr.writeLine "emit_storybook_stories: duplicate StoryBook id " & id
        return 2
      ids.incl id

  let expected = expectedFiles(sections)
  var stale: seq[string]
  if dirExists(outDir):
    for kind, path in walkDir(outDir):
      let name = path.extractFilename
      if kind == pcFile and name notin expected:
        stale.add path
  if check:
    var differs = stale.len > 0
    for name, content in expected:
      let path = outDir / name
      if not fileExists(path) or readFile(path) != content:
        differs = true
        stderr.writeLine "emit_storybook_stories: out of date: " & path
    for path in stale:
      stderr.writeLine "emit_storybook_stories: stale: " & path
    return (if differs: 1 else: 0)

  createDir(outDir)
  for path in stale:
    removeFile(path)
  for name, content in expected:
    let path = outDir / name
    # Rewrite only what changed, so a StoryBook dev server watching the
    # directory reloads only the sections that did.
    if not fileExists(path) or readFile(path) != content:
      writeFile(path, content)
  echo "emit_storybook_stories: ", ids.len, " stories in ", sections.len,
    " sections -> ", outDir
  0

when isMainModule:
  quit(main())
