#!/usr/bin/env bash
#
# reclaim-hook-dispatchers.sh -- after git-hooks.nix's installer, give each hook
# slot back to Reprobuild's dispatcher and chain the pre-commit shim behind it.
#
#   dir="$(bash ci/dev/reclaim-hook-dispatchers.sh snapshot)"   # BEFORE the installer
#   bash ci/dev/reclaim-hook-dispatchers.sh --snapshot "$dir"     # after it
#   bash ci/dev/reclaim-hook-dispatchers.sh                       # after it, no snapshot
#
# `pre-commit install` finds Reprobuild's dispatcher ("# reprobuild hook
# dispatcher") in a slot, moves it to `<hook>.legacy` and writes its own shim
# there. The managed hook -- for pre-push, the publication gate -- then runs
# only because pre-commit's shim chains `.legacy`. Reprobuild's model is the
# reverse: the dispatcher owns `<hook>` and runs the repository's own hook from
# `<hook>.repro-local`. For every `.legacy` dispatcher this script:
#
#   * slot holds a pre-commit/prek shim (or nothing) -> chain the shim as
#     `.repro-local` and put the dispatcher back;
#   * slot already holds a dispatcher -> drop the stale `.legacy` copy;
#   * anything else (a hand-written hook in the slot or in `.repro-local`) ->
#     touch nothing and say so; `repro hooks ensure --vcs` reconciles it.
#
# A DISPATCHER THE INSTALLER DESTROYS. `.legacy` holds ONE file. When another
# hook manager has already displaced the dispatcher -- `prek install` (a
# worktree on an older revision, the portable layer, an agent) leaves prek's
# shim in the slot and the dispatcher at `.legacy` -- git-hooks.nix's installer
# cannot put it back: python `pre-commit uninstall` does not recognise prek's
# shim as its own, so it leaves it, and `pre-commit install` then moves it onto
# `.legacy`, OVERWRITING the dispatcher. The repository is left with pre-commit
# in the slot, no dispatcher, and prek's shim at `.legacy` that pre-commit runs
# in migration mode; the managed hooks stop running. Measured 2026-10-29 with
# this flake's pre-commit 4.3.0 and prek 0.2.17; devops-modules hit the mirror
# image (python pre-commit first, then prek) the same day and fixed it in
# 3793f32f (lib/git-hooks-reprobuild-handoff.nix), which this ports.
#
# So `snapshot`, run BEFORE the installer, copies every dispatcher it finds (in
# the slot, or at `.legacy` behind a generated pre-commit/prek shim) into a
# fresh directory and prints its path. `--snapshot DIR`, after the installer,
# restores from it any dispatcher the installer destroyed, with the same
# chaining and the same refusals as above, and deletes DIR. Once a dispatcher
# is back, a generated pre-commit/prek shim left at `.legacy` behind it is
# removed: it is regenerable, and chained it re-enters migration mode. A
# hand-written `.legacy` is never touched.
#
# A repository with no dispatcher is left exactly as the installer left it.
# Never fails the caller.
#
# Contract suite: ci/test/reclaim-hook-dispatchers-test.sh
set -uo pipefail

say() { echo "reclaim-hook-dispatchers: $*" >&2; }
dispatcher='reprobuild hook dispatcher'
generated='^# File generated by (pre-commit|prek)'

is_dispatcher() { grep -q "$dispatcher" "$1" 2>/dev/null; }
is_generated() { grep -Eq "$generated" "$1" 2>/dev/null; }

if [ "${1:-}" = snapshot ]; then
	hooks="$(git rev-parse --path-format=absolute --git-path hooks 2>/dev/null)" || exit 0
	[ -d "$hooks" ] || exit 0
	snap=""
	for slot in "$hooks"/*; do
		[ -f "$slot" ] || continue
		name="$(basename "$slot")"
		case "$name" in *.*) continue ;; esac
		if is_dispatcher "$slot"; then
			:
		elif is_generated "$slot" && is_dispatcher "$slot.legacy"; then
			slot="$slot.legacy"
		else
			continue
		fi
		if [ -z "$snap" ]; then
			snap="$(mktemp -d "${TMPDIR:-/tmp}/ct-hooks-snapshot.XXXXXX" 2>/dev/null)" || exit 0
			# Restore into the directory the copies came from: the installer
			# rewrites core.hooksPath in between.
			printf '%s\n' "$hooks" >"$snap/.hooks-dir"
		fi
		cp -p "$slot" "$snap/$name" 2>/dev/null || true
	done
	[ -z "$snap" ] || printf '%s\n' "$snap"
	exit 0
fi

snapshot=""
if [ "${1:-}" = --snapshot ]; then
	snapshot="${2:-}"
fi

hooks="$(git rev-parse --path-format=absolute --git-path hooks 2>/dev/null)" || hooks=""
if [ -n "$snapshot" ] && [ -f "$snapshot/.hooks-dir" ]; then
	hooks="$(cat "$snapshot/.hooks-dir")"
fi
if [ -z "$hooks" ] || [ ! -d "$hooks" ]; then
	[ -z "$snapshot" ] || [ ! -f "$snapshot/.hooks-dir" ] || rm -rf -- "${snapshot:?}"
	exit 0
fi

for legacy in "$hooks"/*.legacy; do
	if [ ! -f "$legacy" ] || ! grep -q "$dispatcher" "$legacy"; then
		continue
	fi
	slot="${legacy%.legacy}"
	name="$(basename "$slot")"
	if [ -f "$slot" ] && grep -q "$dispatcher" "$slot"; then
		rm -f "$legacy"
		continue
	fi
	if [ -e "$slot" ] && ! grep -Eq "$generated" "$slot"; then
		say "$name is not a pre-commit shim; leaving the dispatcher at $name.legacy."
		say "  Run 'repro hooks ensure --vcs' to reconcile."
		continue
	fi
	if [ -f "$slot.repro-local" ] && ! grep -Eq "$generated" "$slot.repro-local"; then
		say "$name.repro-local is your own hook; not replacing it with the shim."
		say "  Run 'repro hooks ensure --vcs' to reconcile."
		continue
	fi
	if [ -e "$slot" ]; then
		mv -f "$slot" "$slot.repro-local" || continue
	fi
	mv -f "$legacy" "$slot" || continue
	say "kept the Reprobuild dispatcher at $name (pre-commit chained as $name.repro-local)"
done

# Dispatchers the installer destroyed: restore them from the snapshot. Only a
# directory `snapshot` made (it carries `.hooks-dir`) is read, and deleted.
if [ -n "$snapshot" ] && [ -f "$snapshot/.hooks-dir" ]; then
	for saved in "$snapshot"/*; do
		[ -f "$saved" ] || continue
		name="$(basename "$saved")"
		slot="$hooks/$name"
		if is_dispatcher "$slot" || is_dispatcher "$slot.legacy"; then
			continue
		fi
		if [ -e "$slot" ]; then
			if ! is_generated "$slot"; then
				say "$name was replaced by a hook that is not a pre-commit shim; the dispatcher is gone."
				say "  Run 'repro hooks ensure --vcs' to reconcile."
				continue
			fi
			if [ -f "$slot.repro-local" ] && ! is_generated "$slot.repro-local"; then
				say "$name.repro-local is your own hook; not replacing it with the shim."
				say "  Run 'repro hooks ensure --vcs' to reconcile."
				continue
			fi
			mv -f "$slot" "$slot.repro-local" || continue
			chmod +x "$slot.repro-local" 2>/dev/null || true
		fi
		cp -p "$saved" "$slot" || continue
		chmod +x "$slot" 2>/dev/null || true
		say "restored the Reprobuild dispatcher at $name, which the hook installer had overwritten (pre-commit chained as $name.repro-local)"
	done
	rm -rf -- "${snapshot:?}"
fi

# A generated shim stranded at `.legacy` behind a dispatcher.
for legacy in "$hooks"/*.legacy; do
	[ -f "$legacy" ] || continue
	slot="${legacy%.legacy}"
	if ! is_dispatcher "$slot" || ! is_generated "$legacy"; then
		continue
	fi
	rm -f "$legacy" || continue
	say "removed $(basename "$legacy") (a hook manager shim displaced behind the Reprobuild dispatcher)"
done
exit 0
