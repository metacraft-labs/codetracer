#!/usr/bin/env python3
"""The scenario port's inventory, checked against the tree.

`src/tests/scenarios/inventory/inventory.tsv` classifies every UI test file —
the Playwright specs under src/tests/gui/tests, the terminal's real-terminal
suites, the GPUI suites and the VS Code extension's WebDriverIO suites — as

  user-level  ported to a scenario
  split       ported as a stage plus input steps (it manipulated internals)
  lower-tier  kept as it is, as a lower-tier test (the `note` says why)

Scenarios that port no test — new coverage the pack brings — are listed in
`inventory/new-scenarios.tsv`, each with why.

This check fails when the inventory and the tree disagree in either direction
(a test file nobody classified, a row for a file that is gone and that
no scenario ports — a ported test may be retired, its row stays), when a ported
row names no scenario or a scenario that does not exist, when a scenario is
named by no row, or when the counts in inventory/COUNTS differ from the rows.

  ci/test/scenario-inventory.py            check
  ci/test/scenario-inventory.py --counts   rewrite inventory/COUNTS from the rows
"""
import collections
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
INV = os.path.join(ROOT, "src/tests/scenarios/inventory/inventory.tsv")
COUNTS = os.path.join(ROOT, "src/tests/scenarios/inventory/COUNTS")
# Scenarios that port no existing test: new coverage the pack brings (each
# with its reason, in that file).
NEW = os.path.join(ROOT, "src/tests/scenarios/inventory/new-scenarios.tsv")
SCENARIOS = os.path.join(ROOT, "src/tests/scenarios")
# The VS Code flavour's scenarios live beside its binding, in the extension's
# repository: a row names them `codetracer-vscode-extension:<path>`, checked
# against the sibling checkout when it has them (an older checkout, from
# before the extension had scenarios, cannot say).
EXTENSION_PREFIX = "codetracer-vscode-extension:"
EXTENSION = os.environ.get("CODETRACER_VSCODE_EXTENSION_DIR") or os.path.join(
    os.path.dirname(ROOT), "codetracer-vscode-extension")


def scenario_exists(s):
    if s.startswith(EXTENSION_PREFIX):
        if not os.path.isdir(os.path.join(EXTENSION, "test", "scenarios")):
            return True
        return os.path.isfile(os.path.join(EXTENSION, s[len(EXTENSION_PREFIX):]))
    return os.path.isfile(os.path.join(SCENARIOS, s))
CLASSES = ("user-level", "split", "lower-tier")


def tree_files():
    files = set()
    gui = os.path.join(ROOT, "src/tests/gui/tests")
    for d, _, fs in os.walk(gui):
        for f in fs:
            if f.endswith(".spec.ts"):
                files.add(os.path.relpath(os.path.join(d, f), ROOT))
    for d in ("src/frontend/tui/tests/real_terminal", "src/frontend/gpui/tests"):
        for f in os.listdir(os.path.join(ROOT, d)):
            if f.startswith("test_") and f.endswith(".nim"):
                files.add(f"{d}/{f}")
    return files


def rows():
    with open(INV, newline="") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def counts_text(rs):
    c = collections.Counter((r["flavour"], r["class"]) for r in rs)
    lines = ["# Generated by ci/test/scenario-inventory.py --counts; checked by it.",
             f"total {len(rs)}"]
    for k in CLASSES:
        lines.append(f"{k} {sum(v for (f, cl), v in c.items() if cl == k)}")
    for f in sorted({r['flavour'] for r in rs}):
        for k in CLASSES:
            lines.append(f"{f} {k} {c[(f, k)]}")
    ported = [r for r in rs if r["class"] != "lower-tier"]
    lines.append(f"ported {sum(1 for r in ported if r['scenarios'] not in ('', '-'))} of {len(ported)}")
    return "\n".join(lines) + "\n"


def main():
    rs = rows()
    if len(sys.argv) > 1 and sys.argv[1] == "--counts":
        with open(COUNTS, "w") as fh:
            fh.write(counts_text(rs))
        print(counts_text(rs), end="")
        return 0
    problems = []
    seen = collections.Counter(r["path"] for r in rs)
    for p, n in seen.items():
        if n > 1:
            problems.append(f"{p}: listed {n} times")
    local = {r["path"] for r in rs if not r["path"].startswith("codetracer-vscode-extension:")}
    tree = tree_files()
    for p in sorted(tree - local):
        problems.append(f"{p}: a UI test the inventory does not classify")
    ported_rows = {r["path"] for r in rs
                   if r["class"] != "lower-tier" and r["scenarios"] not in ("", "-")}
    for p in sorted(local - tree):
        # a ported test may be retired: its row stays, naming what ports it
        if p not in ported_rows:
            problems.append(f"{p}: in the inventory but not in the tree")
    named = set()
    for r in rs:
        if r["class"] not in CLASSES:
            problems.append(f"{r['path']}: unknown class {r['class']!r}")
            continue
        sc = [s for s in r["scenarios"].split(",") if s not in ("", "-")]
        if r["class"] == "lower-tier":
            if sc:
                problems.append(f"{r['path']}: lower-tier but names scenarios {sc}")
            if not r["note"] or r["note"] == "-":
                problems.append(f"{r['path']}: lower-tier with no reason")
            continue
        if not sc:
            problems.append(f"{r['path']}: {r['class']}, but no scenario ports it")
        for s in sc:
            named.add(s)
            if not scenario_exists(s):
                problems.append(f"{r['path']}: names {s}, which does not exist")
    if os.path.isfile(NEW):
        with open(NEW, newline="") as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                named.add(r["scenario"])
                if not os.path.isfile(os.path.join(SCENARIOS, r["scenario"])):
                    problems.append(f"new-scenarios.tsv names {r['scenario']}, which does not exist")
                if not r.get("why", "").strip():
                    problems.append(f"new-scenarios.tsv: {r['scenario']} says not why it is new")
    for d, _, fs in os.walk(SCENARIOS):
        rel = os.path.relpath(d, SCENARIOS)
        if rel.split(os.sep)[0] in ("pack", "lanes", "fixtures", "inventory", "bindings",
                                    "stages", "resolver", "captures", "tests"):
            continue
        for f in fs:
            if f.endswith(".yaml"):
                s = os.path.normpath(os.path.join(rel, f))
                if s not in named:
                    problems.append(f"{s}: a scenario no inventory row names")
    if os.path.isfile(COUNTS):
        if open(COUNTS).read() != counts_text(rs):
            problems.append("inventory/COUNTS is stale (ci/test/scenario-inventory.py --counts)")
    else:
        problems.append("inventory/COUNTS is missing")
    for p in problems:
        print("PROBLEM", p)
    print(counts_text(rs), end="")
    print(f"scenario-inventory: {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
