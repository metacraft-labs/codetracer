//! RS-M2 — integration tests for the db-backend span-stream reader,
//! `ct/load-request-spans` paging/filtering, and the read-only legacy JSONL
//! shim.
//!
//! Spec: `codetracer-specs/Trace-Files/CTFS-Request-Span-Streams.md`;
//! milestone RS-M2 in
//! `codetracer-specs/Planned-Features/Request-Panel-Live-Sessions.milestones.org`.
//!
//! # No mocks
//!
//! Every test here runs against a **real `.ct` container written by the
//! canonical Nim writer** (`codetracer-trace-format-nim`'s
//! `multi_stream_writer` + `span_stream`), committed under
//! `tests/fixtures/span_stream/` and regenerated by the `regenerate.sh` next to
//! them. Nothing is mocked, stubbed or faked: the Rust reader under test parses
//! bytes it did not produce, which is the entire point — it is the
//! cross-implementation proof that the Nim writer and this Rust reader agree on
//! the wire format.
//!
//! ## Why the fixtures are not "a container recorded by a real server run"
//!
//! RS-M2's `load_request_spans_from_recorded_container` asks for a container
//! from a real server run. **No recorder emits `span_type: "web-request"`
//! records yet.** Per-language emission is RS-M5…RS-M9 (Python, Ruby, PHP,
//! Elixir, JS), every one of which depends on RS-M4, which depends on *this*
//! milestone — RS-M2 is deliberately the readers-first step of the
//! readers-before-writers rollout the spec mandates for `meta.dat` bit 13
//! ("Old readers reject a span-bearing container outright… plan the rollout
//! accordingly (readers first, then writers)"). The most real writer that
//! exists today is therefore the canonical Nim one, and that is what produced
//! these fixtures. When RS-M5 lands, this file's fixture should be replaced by
//! a recorded Flask/PHP session; the assertions below are written against the
//! record contents rather than against fixture-specific byte offsets so that
//! swap is mechanical.
//!
//! The ground-truth `.expected.jsonl` sidecars are emitted by the generator
//! from the span values it fed the writer — **not** by re-reading the
//! container — so a writer bug cannot make the expectations agree with
//! themselves.

