# The path
# ---------------------------------------------------------------------------

const knownLanguageEntries* = ["noir"]
  ## Rule 0. A second language is one more entry in this array and no change
  ## anywhere else — which is the property the rule exists to buy, and is
  ## checkable because the array is the only place a language appears.

proc isLanguageEntry(segment: string): bool =
  for entry in knownLanguageEntries:
    if entry == segment: return true
  false

proc classifyPath*(path: string): tuple[form: EntryForm, language, locator: string] =
  ## Path → form. Deliberately separate from `resolveEntry`, because §1b.4's
  ## "one rewrite rule ... per-prefix" is generated from the same
  ## classification, and two implementations of "which prefixes exist" is how
  ## a form reaches the SPA in the code and 404s at the CDN.
  let segments = splitOn(trimSlashes(path), '/')
  if segments.len == 0 or (segments.len == 1 and segments[0].len == 0):
    return (efBare, "", "")

  if isLanguageEntry(segments[0]):
    if segments.len == 1: return (efBare, segments[0], "")
    if segments.len == 2 and segments[1].len == 0:
      return (efBare, segments[0], "")
    if segments.len == 2 and segments[1] == "new":
      return (efNew, segments[0], "")
    return (efUnknown, segments[0], "")

  case segments[0]
  of "s":
    if segments.len >= 2 and segments[1].len > 0:
      return (efSnapshot, "", segments[1])
    return (efUnknown, "", "")
  of "p":
    if segments.len >= 2 and segments[1].len > 0:
      return (efProject, "", segments[1])
    return (efUnknown, "", "")
  of "projects":
    if segments.len == 1: return (efProjectList, "", "")
    return (efUnknown, "", "")
  of "collab":
    if segments.len == 3 and segments[1] == "join" and segments[2].len > 0:
      return (efSession, "", segments[2])
    return (efUnknown, "", "")
  else:
    return (efUnknown, "", "")

proc splitProjectLocator*(locator: string): tuple[slug, projectId: string] =
  ## §1b.1: "`/p/hello-world-3f9a2c` resolves on the suffix; the slug is for
  ## humans and is ignored." So the split is at the LAST hyphen, and a locator
  ## with no hyphen is all id and no slug — which is what a project whose name
  ## produced an empty slug looks like.
  let cut = lastIndexOf(locator, '-')
  if cut <= 0: return ("", locator)
  (locator[0 ..< cut], locator[cut + 1 .. ^1])

# ---------------------------------------------------------------------------
# The precedence order — §1b.3
# ---------------------------------------------------------------------------

proc resolveEntry*(request: EntryRequest; local: LocalState;
                   pointerReachable = true): EntryResolution =
  ## §1b.3's six steps, in order.
  ##
  ## `pointerReachable` is the caller's report of whether `current.json` could
  ## be fetched, not something this module discovers. That keeps the module
  ## pure and makes step 2's degradation — "a project link degrades to its last
  ## known state rather than to nothing" — a case in a table rather than a
  ## network test.
  let classified = classifyPath(request.path)
  result.form = classified.form
  result.languageEntry = classified.language
  result.position = parsePosition(request.fragment)

  case classified.form
  of efSnapshot:
    # Step 1. Content-addressed, so it either resolves exactly or is gone.
    result.verdict = evSnapshot
    result.locator = classified.locator
    result.opensAsNewProject = true
  of efProject:
    # Step 2.
    let split = splitProjectLocator(classified.locator)
    result.projectSlug = split.slug
    result.locator = split.projectId
    result.opensAsNewProject = true
    if pointerReachable:
      result.verdict = evProjectPointer
    elif split.projectId in local.cachedSnapshotIds:
      result.verdict = evSnapshot
      result.mayBeStale = true
      result.explanation =
        "this project's pointer could not be refreshed, so it has opened at " &
        "the last version this browser saw; it may be out of date"
    else:
      result.verdict = evTemplate
      result.explanation =
        "the project '" & classified.locator & "' could not be reached and " &
        "this browser has no copy of it, so a new project was opened instead"
    if result.position.coordinate.len > 0 and
       result.verdict == evProjectPointer:
      # §1b.3: "A project link carrying a replay coordinate is a contradiction
      # and is treated as one." Resolved against the current snapshot, and said
      # so, rather than dropped or honoured silently.
      result.explanation =
        "this link carries a position in a recorded run, but a project link " &
        "always opens the latest saved state; the position is applied to " &
        "that and may no longer fit"
  of efProjectList:
    result.verdict = evProjectList
  of efSession:
    result.verdict = evCollabSession
    result.locator = classified.locator
  of efNew:
    # Rule 5's third row.
    result.verdict = evTemplate
    result.replacesHistoryEntry = true
    result.opensAsNewProject = true
  of efBare, efInline, efUnknown:
    let payload = inlinePayload(request.fragment)
    if payload.len > 0:
      # Step 3.
      result.form = efInline
      result.verdict = evInlineProject
      result.locator = payload
      result.opensAsNewProject = true
    elif classified.form == efUnknown:
      # Step 6.
      result.verdict = evTemplate
      result.explanation =
        "'" & request.path & "' is not an address this product serves, so a " &
        "new project was opened instead"
    elif local.hasWorkspace:
      # Step 4, rule 5's second row.
      result.verdict = evLocalWorkspace
      result.locator = local.mostRecentProjectId
    else:
      # Rule 5's first row.
      result.verdict = evTemplate

proc writesOnArrival*(resolution: EntryResolution): bool =
  ## Rule 1, as a value. **Always false**, for every form, and the point of
  ## writing it as a proc rather than as a comment is that
  ## `test_arrival_writes_nothing_and_mints_no_address` can assert it over
  ## every form at once — including forms added later, which is when the rule
  ## will actually be at risk.
  ##
  ## Opening a *project* does write to the local store, but that is a
  ## consequence of the user having arrived, not of the arrival: it happens
  ## after `readyForEditing`, on our side of the network, and touches no
  ## storage of ours in §1b.0's sense.
  false

proc mintsServerIdentifier*(resolution: EntryResolution): bool =
  ## The other half of rule 1. Also always false, and also a value so it can be
  ## asserted over the whole enum.
  false

proc ignoredQuery*(request: EntryRequest): string =
  ## Whatever was in the query string. Returned so a test can show a URL
  ## carrying campaign parameters resolving identically to one without them —
  ## rule 2's "any present are ignored".
  request.query

# ---------------------------------------------------------------------------
# Building links — the other direction, and where rule 2 is easiest to break
# ---------------------------------------------------------------------------

proc encodePosition*(position: Position): string =
  ## Every piece of client state, in the fragment. There is no code path here
  ## that can put anything in a query string, which is what makes
  ## `test_no_user_content_reaches_an_access_log` a property of the builder
  ## rather than an observation about today's call sites.
  var parts: seq[string] = @[]
  if position.file.len > 0:
    if position.line > 0:
      parts.add "f=" & position.file & ":" & $position.line
    else:
      parts.add "f=" & position.file
  if position.view.len > 0: parts.add "view=" & position.view
  if position.coordinate.len > 0: parts.add "t=" & position.coordinate
  if position.test.len > 0: parts.add "test=" & position.test
  if position.session > 0: parts.add "session=" & $position.session
  for i, part in parts:
    if i > 0: result.add "&"
    result.add part

proc snapshotPath*(sourceBundleId: string): string =
  "/s/" & sourceBundleId

proc projectPath*(slug, projectId: string): string =
  if slug.len == 0: "/p/" & projectId else: "/p/" & slug & "-" & projectId

proc entryPath*(language: string): string =
  if language.len == 0: "/" else: "/" & language

proc newProjectPath*(language: string): string =
  if language.len == 0: "/new" else: "/" & language & "/new"
