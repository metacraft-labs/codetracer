## cua_keymap.nim — THE CUA BASE KEYMAP, as data.
##
## Owns: the rows of `codetracer-specs/spec/GUI/CUA-Keymap.md` — VS Code
## 1.105.0's bindings and the desktop's debugger set, the default base
## (Base-Keymaps-And-Layer-Stack.md §3.1) — for every scope: the editor
## (§3.1–§3.4, §3.9), the find widget's pushed layer (§3.5), lists, trees and
## single-line inputs (§3.6), the workbench (§3.7), the overlays' layers
## (§3.8), the legacy-terminal fallbacks (§3.10) and the debugger layer with
## its letters (§4).
##
## Refuses to own: what the rows MEAN (the editing vocabulary,
## `editor/operations.nim`; the catalogue, `operation_catalogue.nim`), how a
## row becomes a binding (`base_rows.nim`), and how a front-end reaches an
## operation (its dispatch).
##
## **NOTHING HERE BUT DATA.** No procedure, no closure, no `case` over keys
## (Base-Keymaps §8 item 3). Each row is spelled as CUA-Keymap.md spells it,
## its abbreviations (`writable`, `ro`, `dl`) expanded, so
## `test_plat68_cua_oracle.nim` compares the two row by row in both
## directions; an edit here that is not an edit there is red.
##
## A row's `table` is where it is installed (`scope_path`): "" the editor,
## `global` the window, `list` / `input` / `pane:<kind>` the focused
## element's, `find` / `palette` / `context-menu` a pushed layer's.

