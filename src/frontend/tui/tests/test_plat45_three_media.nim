## test_plat45_three_media.nim — PLAT-45. **Same panes, same places, three
## media**, each read from its OWN output.
##
## PLAT-45's first real-stack row: open the `calc` recording in every
## front-end at depth 0 — the desktop, the GPUI window, the terminal at
## ultra-wide — read the arrangement from what each one PRODUCED, reduce each
## to PLAT-20's medium-independent relation (pairwise BEFORE, stack membership;
## `headless_app/arrangement_relation`), and require all three to equal the
## shared tree's relation. Comparing the model with itself is the trap
## Verification-Harness-Traps §4a names, so no medium's side is derived from
## the `Layout` it was given:
##
##   * **terminal** — a real session on `calc` in this process (the host's own
##     `openTuiSession`, a real `replay-server`), painted at 300x80: the
##     `CellArea` rectangles of the frame (`ShellScreen.projection`), and each
##     stacked region's active tab read back off the PAINTED strip;
##   * **GPUI** — the windowed `codetracer-gpui` on `calc`, in a real window
##     on a headless sway, READ OFF ITS PIXELS by PLAT-39's reader
##     (`ci/test/plat45-arrangement-window.sh` frames it,
##     `screen_oracle/plat45_window_record.nim` locates the cells from the
##     gutters and OCRs each cell's tab strip and heading) into
##     `src/tests/visual/plat45-gpui-arrangement.json`. Also the shipped
##     binary's dock document (`--dock-out`) and its render plan, so a window
##     that drew something other than what it was told is caught by the
##     difference between the two;
##   * **desktop** — the real Electron app, captured by `just
##     plat45-capture-electron` into
##     `src/tests/visual/answers/plat45-default-arrangement.electron.json`: every
##     GoldenLayout stack's DOM rectangle with its tabs' `Content` ordinals, on
##     the product's FIRST-RUN path (no user layout), plus the config as
##     loaded. The file's absence FAILS by name, naming the recipe.
##
## The same record carries a second capture from a prefix whose default was
## GENERATED BY A SCRATCH BUILD of the shared tree with one edit (the right
## column's two stacks swapped): the desktop's default must change with the
## tree, which is what makes `default_layout.json` an output of the tree and
## not a copy of it.
##
## No mocks: a real recording, real processes, real files.

